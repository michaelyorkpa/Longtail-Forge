import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);
const rootDir = path.resolve(process.env.LTF_MODULE_REGISTRY_ROOT || path.dirname(scriptPath), process.env.LTF_MODULE_REGISTRY_ROOT ? "." : "..");
const modulesDir = path.join(rootDir, "src", "modules");
const catalogPath = path.join(rootDir, "src", "core", "modules", "bundled-module-catalog.generated.js");
const checkOnly = process.argv.includes("--check");

const directoryNames = await discoverModuleDirectoryNames();
const generatedSource = renderCatalog(directoryNames);

if (checkOnly) {
  const currentSource = await readCurrentCatalog();
  if (currentSource !== generatedSource) {
    console.error("Bundled module catalog is stale. Run npm run modules:registry:generate.");
    process.exitCode = 1;
  } else {
    console.log(`Bundled module catalog is current (${directoryNames.length} modules).`);
  }
} else {
  await fs.writeFile(catalogPath, generatedSource, "utf8");
  console.log(`Generated bundled module catalog with ${directoryNames.length} modules.`);
}

async function discoverModuleDirectoryNames() {
  const entries = await fs.readdir(modulesDir, { withFileTypes: true });
  const names = [];

  for (const entry of entries) {
    if (!entry.isDirectory()) {
      continue;
    }
    try {
      const moduleFile = path.join(modulesDir, entry.name, "module.js");
      const stat = await fs.stat(moduleFile);
      if (stat.isFile()) {
        names.push(entry.name);
      }
    } catch (error) {
      if (/** @type {NodeJS.ErrnoException} */ (error).code !== "ENOENT") {
        throw error;
      }
    }
  }

  return names.sort((left, right) => left.localeCompare(right));
}

/** @param {readonly string[]} directoryNames */
function renderCatalog(directoryNames) {
  const imports = directoryNames.map((directoryName, index) => (
    `import { moduleEntry as moduleEntry${index} } from "../../modules/${directoryName}/module.js";`
  ));
  const entries = directoryNames.map((directoryName, index) => (
    `  Object.freeze({ directoryName: "${directoryName}", moduleEntry: moduleEntry${index} }),`
  ));

  return [
    "// Generated by scripts/generate-bundled-module-catalog.mjs. Do not edit by hand.",
    ...imports,
    "",
    "const bundledModuleCatalog = Object.freeze([",
    ...entries,
    "]);",
    "",
    "export { bundledModuleCatalog };",
    "",
  ].join("\n");
}

async function readCurrentCatalog() {
  try {
    return await fs.readFile(catalogPath, "utf8");
  } catch (error) {
    if (/** @type {NodeJS.ErrnoException} */ (error).code === "ENOENT") {
      return "";
    }
    throw error;
  }
}
