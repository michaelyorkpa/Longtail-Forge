const INVENTORY_START = "<!-- GENERATED REGRESSION INVENTORY START -->";
const INVENTORY_END = "<!-- GENERATED REGRESSION INVENTORY END -->";
const INVENTORY_GENERATOR = "node scripts/generate-regression-doc-inventory.mjs";

function buildRegressionDocInventory({ manifest, policy }) {
  const credited = manifest.retiredRegressions.filter((entry) => entry.floorCredit === true);
  const activeAreaCounts = manifest.summary.areaCounts;
  const creditedAreaCounts = countBy(credited.filter((entry) => entry.area), (entry) => entry.area);
  const conventionPathCount = manifest.summary.discoveredScripts - manifest.summary.legacyScripts;
  const areaRows = CANONICAL_REGRESSION_AREAS
    .map((area) => tableRow([
      `\`${area}\``,
      activeAreaCounts[area] || 0,
      creditedAreaCounts[area] || 0,
      policy.minimumAreaScripts[area],
    ]));
  const tierRows = CANONICAL_REGRESSION_TIERS
    .map((tier) => tableRow([`\`${tier}\``, manifest.summary.tierCounts[tier] || 0]));
  const runModeRows = CANONICAL_REGRESSION_RUN_MODES
    .map((runMode) => tableRow([`\`${runMode}\``, manifest.summary.runModeCounts[runMode] || 0]));
  const familyRows = manifest.coverageFamilies.map((family) => {
    const matchTags = policy.coverageFamilies.find((entry) => entry.id === family.id)?.matchTags || [];
    const creditedCount = credited.filter((entry) => (
      matchTags.every((tag) => retirementTags(entry).includes(tag))
    )).length;
    return tableRow([
      `\`${family.id}\``,
      family.activeRegressionIds.length,
      creditedCount,
      family.minimumActiveScripts,
    ]);
  });

  return [
    INVENTORY_START,
    `<!-- Generated by \`${INVENTORY_GENERATOR} --write\`; edit only through discovery metadata or the reviewed floor policy. -->`,
    "### Generated coverage inventory",
    "",
    "The active-script and legacy ceilings only move downward. Assertion, area, release-gate, and family floors only move upward; credited retirements require generated assertion inventory plus named behavior owners.",
    "",
    "| Inventory | Count |",
    "| --- | ---: |",
    tableRow(["Active discovered regressions", manifest.summary.discoveredScripts]),
    tableRow(["Legacy-snapshot regressions", manifest.summary.legacyScripts]),
    tableRow(["Convention-path metadata regressions", conventionPathCount]),
    tableRow(["Credited retirements", credited.length]),
    tableRow(["Active release-gate regressions", manifest.summary.releaseGateScripts]),
    tableRow(["Required active release-gate IDs", policy.requiredReleaseGateIds.length]),
    tableRow(["Active regression ceiling", policy.maximumActiveScripts]),
    tableRow(["Legacy regression ceiling", policy.legacyMetadataException.maximumScripts]),
    tableRow(["Active regression assertions", manifest.assertionInventory.activeAssertionCount]),
    tableRow(["Vitest owner assertions", manifest.assertionInventory.vitestAssertionCount]),
    tableRow(["Direct owner assertions", manifest.assertionInventory.directOwnerAssertionCount]),
    tableRow(["Credited reviewed assertion reductions", manifest.assertionInventory.creditedAssertionReduction]),
    tableRow(["Effective assertion floor", policy.minimumAssertionCount]),
    tableRow(["Release-gate ratchet floor", policy.minimumReleaseGateScripts]),
    "",
    "| Canonical area | Active | Credits | Ratchet floor |",
    "| --- | ---: | ---: | ---: |",
    ...areaRows,
    "",
    "| Canonical tier | Active |",
    "| --- | ---: |",
    ...tierRows,
    "",
    "| Run mode | Active |",
    "| --- | ---: |",
    ...runModeRows,
    "",
    "| Coverage family | Active | Credits | Ratchet floor |",
    "| --- | ---: | ---: | ---: |",
    ...familyRows,
    INVENTORY_END,
  ].join("\n");
}

function replaceRegressionDocInventory(source, block) {
  const startIndex = source.indexOf(INVENTORY_START);
  const endIndex = source.indexOf(INVENTORY_END);
  if (startIndex < 0 || endIndex < startIndex) {
    throw new Error("Regression suite documentation is missing the generated inventory delimiters.");
  }
  if (source.indexOf(INVENTORY_START, startIndex + INVENTORY_START.length) >= 0
    || source.indexOf(INVENTORY_END, endIndex + INVENTORY_END.length) >= 0) {
    throw new Error("Regression suite documentation should contain exactly one generated inventory block.");
  }
  return `${source.slice(0, startIndex)}${block}${source.slice(endIndex + INVENTORY_END.length)}`;
}

function tableRow(values) {
  return `| ${values.join(" | ")} |`;
}

function countBy(values, getKey) {
  const counts = {};
  for (const value of values) {
    const key = getKey(value);
    counts[key] = (counts[key] || 0) + 1;
  }
  return counts;
}

function retirementTags(entry) {
  if (Array.isArray(entry.tags)) {
    return entry.tags;
  }
  return /-closeout-regression\.mjs$/.test(entry.script || "") ? ["closeout"] : [];
}

export {
  INVENTORY_END,
  INVENTORY_GENERATOR,
  INVENTORY_START,
  buildRegressionDocInventory,
  replaceRegressionDocInventory,
};
import {
  CANONICAL_REGRESSION_AREAS,
  CANONICAL_REGRESSION_RUN_MODES,
  CANONICAL_REGRESSION_TIERS,
} from "./regression-metadata.mjs";
